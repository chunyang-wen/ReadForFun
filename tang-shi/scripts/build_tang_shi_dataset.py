def build_full_dataset() -> None:
    print(f"Building full dataset with {len(POEMS_RAW)} poems...")
    poems: list[dict] = []
    total_images = 0

    for poem_dict in POEMS_RAW:
        title = poem_dict["title"]
        poet = poem_dict["poet"]
        slug = manage_tang_shi.slugify(f"{poet}-{title}")

        lines_data = []
        total_lines = len(poem_dict["lines"])
        for idx, line_info in enumerate(poem_dict["lines"]):
            text = line_info["text"].strip()
            pinyin = manage_tang_shi.pinyin_for_text(text)
            img_rel = f"images/{slug}/line_{idx+1}.svg"

            lines_data.append({
                "line_no": idx + 1,
                "text": text,
                "pinyin": pinyin,
                "translation": line_info.get("translation", ""),
                "explanation": line_info.get("explanation", ""),
                "image": img_rel,
                "image_prompt": f"Traditional Chinese ink-and-wash painting illustrating Tang poem line: {text}, mood of {title}, oriental aesthetic, masterwork watercolor.",
            })

        poem_record = {
            "id": slug,
            "title": title,
            "title_pinyin": manage_tang_shi.pinyin_for_text(title),
            "poet": poet,
            "poet_pinyin": manage_tang_shi.pinyin_for_text(poet),
            "dynasty": "唐",
            "form": poem_dict.get("form", "五言绝句"),
            "tags": poem_dict.get("tags", ["唐诗", "经典"]),
            "appreciation": poem_dict.get("appreciation", ""),
            "lines": lines_data,
        }

        # Build images
        p_dir = IMAGES_DIR / slug
        p_dir.mkdir(parents=True, exist_ok=True)
        for idx, line in enumerate(lines_data):
            svg_content = manage_tang_shi.generate_ink_illustration_svg(
                title=title,
                line_text=line["text"],
                line_index=idx,
                total_lines=total_lines,
                mood_tags=poem_record["tags"],
                palette_seed=len(slug) + idx * 3,
            )
            svg_file = TANG_SHI_DIR / line["image"]
            svg_file.write_text(svg_content, encoding="utf-8")
            total_images += 1

        poems.append(poem_record)

    manage_tang_shi.save_poems(poems)
    print(f"Finished: {len(poems)} poems, {total_images} line images generated successfully!")


if __name__ == "__main__":
    build_full_dataset()
